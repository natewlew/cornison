#!/usr/bin/env python3
"""Build the FR4 switch-plate KiCad projects for JLCPCB, from the exact
same geometry as the POM/case build (case/out/plate-fr4ref-{side}.dxf,
produced by case.py) -- so what gets ordered as FR4 matches what the 3D
preview and the POM/laser DXF already show, with nothing hand-redrawn.

Run with the same environment as case.py, from the repo root:
  ./build.sh fr4

(Only needs ezdxf, which build123d already pulls in -- no pcbnew/KiCad
python needed, since this writes raw Edge.Cuts graphics, not footprints.)
"""
import os
import uuid

from dxf_to_loops import dxf_to_loops

CASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(CASE_DIR, "out")
# The board version (repo root VERSION): the plate carries the number of the
# PCB revision it fits. pcb/sync_version.py keeps everything else in step.
VERSION = open(os.path.join(os.path.dirname(CASE_DIR), "VERSION")).read().strip()
PLATE_THICKNESS = 1.6  # mm, matches case.py's FR4_PLATE_T

LAYERS_BLOCK = """\t(layers
\t\t(0 "F.Cu" signal)
\t\t(2 "B.Cu" signal)
\t\t(9 "F.Adhes" user "F.Adhesive")
\t\t(11 "B.Adhes" user "B.Adhesive")
\t\t(13 "F.Paste" user)
\t\t(15 "B.Paste" user)
\t\t(5 "F.SilkS" user "F.Silkscreen")
\t\t(7 "B.SilkS" user "B.Silkscreen")
\t\t(1 "F.Mask" user)
\t\t(3 "B.Mask" user)
\t\t(17 "Dwgs.User" user "User.Drawings")
\t\t(19 "Cmts.User" user "User.Comments")
\t\t(21 "Eco1.User" user "User.Eco1")
\t\t(23 "Eco2.User" user "User.Eco2")
\t\t(25 "Edge.Cuts" user)
\t\t(27 "Margin" user)
\t\t(31 "F.CrtYd" user "F.Courtyard")
\t\t(29 "B.CrtYd" user "B.Courtyard")
\t\t(35 "F.Fab" user)
\t\t(33 "B.Fab" user)
\t)"""


def gr_line(x1, y1, x2, y2):
    return (
        f'\t(gr_line (start {x1:.4f} {y1:.4f}) (end {x2:.4f} {y2:.4f}) '
        f'(layer "Edge.Cuts") (width 0.1) (tstamp {uuid.uuid4()}))'
    )


def loop_to_lines(loop):
    lines = []
    n = len(loop)
    for i in range(n):
        x1, y1 = loop[i]
        x2, y2 = loop[(i + 1) % n]
        if abs(x1 - x2) < 1e-6 and abs(y1 - y2) < 1e-6:
            continue
        lines.append(gr_line(x1, y1, x2, y2))
    return lines


def build_pcb(side, loops, title):
    lines = []
    for loop in [loops["outer"], *loops["holes"]]:
        lines.extend(loop_to_lines(loop))

    return f"""(kicad_pcb
\t(version 20260206)
\t(generator "pcbnew")
\t(generator_version "10.0")
\t(general
\t\t(thickness {PLATE_THICKNESS})
\t\t(legacy_teardrops no)
\t)
\t(paper "A4")
\t(title_block
\t\t(title "{title}")
\t\t(rev "{VERSION}")
\t\t(company "natewlew")
\t\t(comment 1 "Generated by case/scripts/make_fr4_plate.py -- do not hand-edit, re-run the generator instead")
\t\t(comment 2 "Switch plate for Cornison PCB v{VERSION}")
\t)
{LAYERS_BLOCK}
\t(setup
\t\t(pad_to_mask_clearance 0.2)
\t)
\t(net 0 "")
{chr(10).join(lines)}
)
"""


PRO_TEMPLATE = """{{
  "board": {{
    "design_settings": {{
      "defaults": {{
        "board_outline_line_width": 0.1,
        "silk_line_width": 0.15
      }}
    }}
  }},
  "meta": {{
    "filename": "{basename}.kicad_pro",
    "version": 1
  }}
}}
"""

FP_LIB_TABLE = """(fp_lib_table
  (lib (name kbd)(type KiCad)(uri ${KIPRJMOD}/../../pcb/kbd/kicad-footprints/kbd.pretty)(options "")(descr ""))
)
"""


def main():
    for side in ("left", "right"):
        dxf_path = os.path.join(OUT_DIR, f"plate-fr4ref-{side}.dxf")
        loops = dxf_to_loops(dxf_path)
        print(f"{side}: outer {len(loops['outer'])} pts, {len(loops['holes'])} holes")

        proj_dir = os.path.join(CASE_DIR, f"plate-fr4-{side}")
        os.makedirs(proj_dir, exist_ok=True)
        basename = f"plate-fr4-{side}"

        title = f"Cornison FR4 Plate ({side.capitalize()})"
        pcb_text = build_pcb(side, loops, title)
        pcb_path = os.path.join(proj_dir, f"{basename}.kicad_pcb")
        open(pcb_path, "w").write(pcb_text)

        pro_path = os.path.join(proj_dir, f"{basename}.kicad_pro")
        open(pro_path, "w").write(PRO_TEMPLATE.format(basename=basename))

        fp_lib_path = os.path.join(proj_dir, "fp-lib-table")
        open(fp_lib_path, "w").write(FP_LIB_TABLE)

        print(f"  wrote {pcb_path}")
        print(f"  wrote {pro_path}")
        print(f"  wrote {fp_lib_path}")


if __name__ == "__main__":
    main()
